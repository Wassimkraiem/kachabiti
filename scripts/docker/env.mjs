// Writes .env.docker for the local Docker setup (docs/DOCKER.md).
// Usage: node scripts/docker/env.mjs   (keeps an existing file)
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';

const FILE = '.env.docker';
if (existsSync(FILE)) {
    console.log(`${FILE} already exists; delete it to regenerate.`);
    process.exit(0);
}

writeFileSync(
    FILE,
    `# Local Docker setup only (docs/DOCKER.md). Generated by scripts/docker/env.mjs; never put live keys here.
ENV=local
NEXT_PUBLIC_SITE_URL=http://localhost:3000
# Signs session cookies (NestJS auth API); the web container needs the same value.
AUTH_SECRET=${randomBytes(32).toString('base64url')}
# The db service in docker-compose.yml (from this machine: localhost:5433).
DATABASE_URL=postgresql://kachabity:kachabity-local@db:5432/kachabity
# Comma-separated e-mails that get the owner role (sign in with the same password as on the live site
# after importing live data).
OWNER_EMAILS=
ADMIN_EMAILS=
NEST_URL=http://localhost:4000
REVALIDATE_SECRET=${crypto.randomUUID()}
# File storage: the local S3-compatible storage in docker-compose.yml (Cloudflare R2 in production).
S3_ENDPOINT=http://localhost:9000
S3_ACCESS_KEY_ID=kachabity-local
S3_SECRET_ACCESS_KEY=kachabity-local-secret
FILES_PUBLIC_URL=http://localhost:9000/products
# npm run docker:import copies a database (read only) into the local one: the server's Postgres,
# e.g. postgresql://user:password@host:5432/db (used from a container: host.docker.internal for
# this machine). Local accounts all get LOCAL_PASSWORD.
SOURCE_DATABASE_URL=
LOCAL_PASSWORD=Kachabity-local-1
`
);
console.log(`Wrote ${FILE}.`);
